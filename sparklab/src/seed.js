function seedAdmin() {
  if (get('SELECT id FROM users WHERE role = ?', 'admin')) return;
  let pw = config.seedAdminPassword;
  let generated = false;
  if (!pw) {
    pw = `SL-${randomToken(9)}`;
    generated = true;
  }
  const id = run('INSERT INTO users (name, email, phone, password_hash, role, is_active, created_at) VALUES (?,?,?,?,?,1,?)',
    config.seedAdminName, config.seedAdminEmail.toLowerCase(), null, hashPassword(pw), 'admin', NOW()).lastId;
  if (generated) {
    const f = path.join(config.dataDir, 'seed-credentials.txt');
    fs.writeFileSync(f, `Spark Lab seed admin\nemail: ${config.seedAdminEmail}\npassword: ${pw}\ncreated: ${NOW()}\n\nاین فایل فقط در محیط تست تولید می‌شود. پس از اولین ورود رمز را تغییر دهید و فایل را حذف کنید.\n`, { mode: 0o600 });
    console.log(`\n╔══════════════════════════════════════════════╗`);
    console.log(`║  مدیر اولیه ساخته شد (رمز تصادفی)            ║`);
    console.log(`║  email: ${config.seedAdminEmail.padEnd(36)}║`);
    console.log(`║  password: ${pw.padEnd(32)}║`);
    console.log(`║  → ذخیره در data/seed-credentials.txt        ║`);
    console.log(`╚══════════════════════════════════════════════╝\n`);
  } else {
    console.log(`Seed admin ready: ${config.seedAdminEmail} (password from .env SEED_ADMIN_PASSWORD)`);
  }
}

