function seedCatalog() {
  const catCount = get('SELECT COUNT(*) AS c FROM categories').c;
  if (catCount === 0) {
    for (const c of CATEGORIES) {
      run('INSERT INTO categories (name, slug, description, icon, sort_order, is_active, created_at) VALUES (?,?,?,?,?,1,?)',
        c.name, c.slug, c.desc, c.icon, c.sort, NOW());
    }
    console.log(`seeded ${CATEGORIES.length} categories`);
  }
  const pCount = get('SELECT COUNT(*) AS c FROM products').c;
  if (pCount === 0) {
    for (const p of PRODUCTS) {
      const cat = get('SELECT id FROM categories WHERE slug = ?', p.cat);
      const id = run(
        `INSERT INTO products
         (category_id, title, slug, summary, description_html, features_json, requirements_text, compatibility_text,
          license_type, license_note, support_terms, faq_json, price, discount_price, version, images_json, cover_image,
          is_featured, is_active, created_at)
         VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?, ?,1,?)`,
        cat ? cat.id : null, p.title, p.slug, p.summary, p.desc, JSON.stringify(p.features),
        p.requirements, p.compatibility, p.license, p.licenseNote, p.support, JSON.stringify(p.faq),
        p.price, p.discount, p.version, JSON.stringify([p.cover]), p.cover, p.featured, NOW()
      ).lastId;
      // register the seeded delivery package
      const zip = p.file;
      const zipPath = path.join(config.privateFilesDir, zip);
      if (fs.existsSync(zipPath)) {
        const st = fs.statSync(zipPath);
        const sha = crypto.createHash('sha256').update(fs.readFileSync(zipPath)).digest('hex');
        run(`INSERT INTO product_files (product_id, version, label, original_name, stored_name, mime, size, sha256, is_active, created_at)
             VALUES (?,?,?,?,?,?,?,?,1,?)`,
          id, p.version, 'بسته کامل محصول', zip.replace(/^seed-/, ''), zip, 'application/zip', st.size, sha, NOW());
      } else {
        console.warn(`package missing for ${p.slug}: ${zip}`);
      }
    }
    console.log(`seeded ${PRODUCTS.length} products with delivery packages`);
  }
}

